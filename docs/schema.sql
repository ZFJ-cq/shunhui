CREATE DATABASE IF NOT EXISTS meeting CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE meeting;
-- The runtime stores domain JSON rows so SQLite and MySQL share an adapter.
-- Only primary-key indexes exist; all domain queries currently run in the single API process.
CREATE TABLE IF NOT EXISTS users (id VARCHAR(80) PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS meetings (id VARCHAR(80) PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS participants (id VARCHAR(80) PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chats (id VARCHAR(80) PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (id VARCHAR(80) PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
